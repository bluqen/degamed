export const FONT_CHARS = Object.keys(G).join('');
export const FONT_KEY = '__dg_font';
/** Glyph cell including the 1px outline on every side. */
export const FONT_CELL = { width: 7, height: 9 };
/** Glyphs overlap their outlines: 6px per character. */
export const FONT_LETTER_SPACING = -1;

/** Normalises text to what the font can draw (upper case, unknown characters become '?'). */
export function fontSafe(text: string): string {
  let out = '';
  for (const ch of text.toUpperCase()) out += ch === '\n' || G[ch] ? ch : ch.trim() ? '?' : ' ';
  return out;
}

/** Width in pixels of a line drawn at scale 1. */
export function fontWidth(text: string): number {
  const n = [...text].length;
  return n ? n * (FONT_CELL.width + FONT_LETTER_SPACING) - FONT_LETTER_SPACING : 0;
}

/** Draws the font sheet: white glyphs with a dark outline, one row. */
export function drawFontSheet(ctx: CanvasRenderingContext2D, outline = '#14141c') {
  const chars = [...FONT_CHARS];
  const { width: cw, height: ch } = FONT_CELL;
  chars.forEach((c, i) => {
    const rows = G[c]!.split(' ');
    const ox = i * cw + 1;
    const on = (x: number, y: number) => y >= 0 && y < 7 && x >= 0 && x < 5 && rows[y]![x] === '1';
    ctx.fillStyle = outline;
    for (let y = -1; y <= 7; y++)
      for (let x = -1; x <= 5; x++) {
        if (on(x, y)) continue;
        if (on(x - 1, y) || on(x + 1, y) || on(x, y - 1) || on(x, y + 1) || on(x - 1, y - 1) || on(x + 1, y + 1) || on(x - 1, y + 1) || on(x + 1, y - 1))
          ctx.fillRect(ox + x, 1 + y, 1, 1);
      }
    ctx.fillStyle = '#ffffff';
    for (let y = 0; y < 7; y++) for (let x = 0; x < 5; x++) if (on(x, y)) ctx.fillRect(ox + x, 1 + y, 1, 1);
  });
  return { width: chars.length * cw, height: ch };
}
